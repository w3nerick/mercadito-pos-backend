create table public.categoria_rapida (
  id_categoria_rapida  bigint generated by default as identity primary key,
  id_sucursal          bigint      not null references public.sucursal,
  nombre               varchar(30) not null,
  color                varchar(9),
  icono                varchar(30),
  orden                int         not null default 0,
  unique (id_sucursal, nombre)
);

create table public.boton_rapido (
  id_boton             bigint generated by default as identity primary key,
  id_categoria_rapida  bigint  not null references public.categoria_rapida on delete cascade,
  id_producto          bigint  not null references public.producto,
  orden                int     not null default 0,
  foto_url             text,
  automatico           boolean not null default false,
  unique (id_categoria_rapida, id_producto)
);

create table public.etiqueta_cola (
  id_etiqueta  bigint generated by default as identity primary key,
  id_producto  bigint      not null references public.producto,
  tipo         varchar(10) not null default 'PRODUCTO' check (tipo in ('PRODUCTO', 'ANAQUEL')),
  motivo       varchar(15) not null check (motivo in ('CODIGO_NUEVO', 'CAMBIO_PRECIO', 'PROMOCION', 'RECEPCION')),
  cantidad     int         not null default 1 check (cantidad > 0),
  estado       varchar(10) not null default 'PENDIENTE' check (estado in ('PENDIENTE', 'IMPRESA')),
  creado       timestamptz not null default now()
);
create index etiqueta_cola_pendiente_idx on public.etiqueta_cola (estado) where estado = 'PENDIENTE';
