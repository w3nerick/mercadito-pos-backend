create table public.ajuste_inventario (
  id_ajuste    bigint generated by default as identity primary key,
  id_almacen   bigint       not null references public.almacen,
  motivo       varchar(12)  not null check (motivo in ('CADUCIDAD', 'DAÑO', 'ROBO', 'CONSUMO', 'CORRECCION')),
  comentario   varchar(250),
  estado       varchar(10)  not null default 'PENDIENTE' check (estado in ('PENDIENTE', 'APLICADO', 'RECHAZADO')),
  id_usuario   bigint       not null references public.usuario,
  id_autoriza  bigint       references public.usuario,
  fecha        timestamptz  not null default now(),
  check (id_autoriza is null or id_autoriza <> id_usuario)          -- RN-ROL-01
);

create table public.ajuste_detalle (
  id_ajuste    bigint        not null references public.ajuste_inventario on delete cascade,
  id_producto  bigint        not null references public.producto,
  id_lote      bigint        references public.lote,
  cantidad     numeric(12,3) not null check (cantidad <> 0),        -- ± según el ajuste
  costo        numeric(12,4),
  primary key (id_ajuste, id_producto)
);

-- Fase 2 (doc 07 §3.1): transferencias y conteos. Se dejan modelados.
create table public.transferencia (
  id_transferencia    bigint generated by default as identity primary key,
  id_almacen_origen   bigint      not null references public.almacen,
  id_almacen_destino  bigint      not null references public.almacen,
  estado              varchar(10) not null default 'SOLICITADA'
                      check (estado in ('SOLICITADA', 'ENVIADA', 'RECIBIDA', 'CANCELADA')),
  fecha_envio         timestamptz,
  fecha_recepcion     timestamptz,
  check (id_almacen_origen <> id_almacen_destino)
);

create table public.transferencia_detalle (
  id_transferencia   bigint        not null references public.transferencia on delete cascade,
  id_producto        bigint        not null references public.producto,
  cantidad_enviada   numeric(12,3) not null check (cantidad_enviada > 0),
  cantidad_recibida  numeric(12,3) check (cantidad_recibida >= 0),
  primary key (id_transferencia, id_producto)
);

create table public.conteo_fisico (
  id_conteo    bigint generated by default as identity primary key,
  id_almacen   bigint      not null references public.almacen,
  tipo         varchar(8)  not null check (tipo in ('TOTAL', 'CICLICO')),
  estado       varchar(8)  not null default 'ABIERTO' check (estado in ('ABIERTO', 'CERRADO', 'APLICADO')),
  fecha_corte  timestamptz not null default now()
);

create table public.conteo_detalle (
  id_conteo    bigint        not null references public.conteo_fisico on delete cascade,
  id_producto  bigint        not null references public.producto,
  teorico      numeric(12,3) not null,
  contado      numeric(12,3),
  diferencia   numeric(12,3) generated always as (contado - teorico) stored,
  primary key (id_conteo, id_producto)
);
